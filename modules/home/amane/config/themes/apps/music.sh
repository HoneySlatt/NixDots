switch_music() {
  local theme_dir="${XDG_CONFIG_HOME:-$HOME/.config}/music"
  local theme_file="$theme_dir/theme.toml" theme_tmp
  mkdir -p "$theme_dir" || return 1
  theme_tmp="$(mktemp "${theme_file}.XXXXXX")" || return 1

  # Keep anything outside the colour table when replacing it.
  if [ -f "$theme_file" ]; then
    if ! awk '
      /^[[:space:]]*\[/ { colors = ($0 ~ /^[[:space:]]*\[colors\][[:space:]]*(#.*)?$/) }
      !colors { print }
    ' "$theme_file" > "$theme_tmp"; then
      rm -f "$theme_tmp"
      return 1
    fi
  fi

  local light="false"
  [ "${C[light]:-false}" = "true" ] && light="true"

  # The accent also colours text and icons (the playing title, active buttons), so
  # it is the palette's accent, not accent_ui: Music picks black or white text
  # for filled accent controls itself.
  local accent="${C[accent]}"

  # Music watches this file and recolours in place while its appearance is Amane.
  if cat >> "$theme_tmp" << EOF
[colors]
# ${C[name]} — auto-generated by switch-theme.sh
light = $light
base = "${C[base]}"
mantle = "${C[mantle]}"
crust = "${C[crust]}"
surface0 = "${C[surface0]}"
surface1 = "${C[surface1]}"
surface2 = "${C[surface2]}"
overlay0 = "${C[overlay0]}"
overlay1 = "${C[overlay1]}"
text = "${C[text]}"
subtext0 = "${C[subtext0]}"
accent = "$accent"
mauve = "${C[mauve]}"
red = "${C[red]}"
green = "${C[green]}"
yellow = "${C[yellow]}"
EOF
  then
    mv "$theme_tmp" "$theme_file"
  else
    rm -f "$theme_tmp"
    return 1
  fi
}
