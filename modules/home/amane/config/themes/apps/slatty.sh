switch_slatty() {
  local theme_dir="${XDG_CONFIG_HOME:-$HOME/.config}/slatty"
  local theme_file="$theme_dir/theme.toml" theme_tmp
  mkdir -p "$theme_dir" || return 1
  theme_tmp="$(mktemp "${theme_file}.XXXXXX")" || return 1

  # Keep the user's shape and motion settings when replacing the colour table.
  if [ -f "$theme_file" ]; then
    if ! awk '
      /^[[:space:]]*\[/ { colors = ($0 ~ /^[[:space:]]*\[colors\][[:space:]]*(#.*)?$/) }
      !colors { print }
    ' "$theme_file" > "$theme_tmp"; then
      rm -f "$theme_tmp"
      return 1
    fi
  fi

  local accent_hex="${C[accent]#\#}" on_accent
  on_accent="$(awk -v r="$((16#${accent_hex:0:2}))" \
    -v g="$((16#${accent_hex:2:2}))" -v b="$((16#${accent_hex:4:2}))" '
    function linear(c) { c /= 255; return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ^ 2.4 }
    BEGIN { l = 0.2126 * linear(r) + 0.7152 * linear(g) + 0.0722 * linear(b);
      print (l > 0.179 ? "#000000" : "#ffffff") }
  ')"

  # Slatty reads this at startup or through Settings → Appearance → Reload.
  if cat >> "$theme_tmp" << EOF
[colors]
# ${C[name]} — auto-generated by switch-theme.sh
background = "${C[base]}"
surface = "${C[mantle]}"
surface_high = "${C[surface0]}"
outline = "${C[surface1]}"
accent = "${C[accent]}"
accent_hover = "${C[accent]}"
on_accent = "$on_accent"
text = "${C[text]}"
muted = "${C[subtext0]}"
success = "${C[green]}"
warning = "${C[yellow]}"
danger = "${C[red]}"
danger_hover = "${C[maroon]}"
error_surface = "${C[surface0]}"
scrim = "${C[crust]}b3"
EOF
  then
    mv "$theme_tmp" "$theme_file"
  else
    rm -f "$theme_tmp"
    return 1
  fi
}
